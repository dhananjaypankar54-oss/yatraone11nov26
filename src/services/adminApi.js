import api from './api.js'
const form = (headers = {}) => ({ headers: { ...headers, 'Content-Type': 'multipart/form-data' } })
export const adminApi = {
  dashboard: () => api.get('/admin/dashboard'),
  users: (params) => api.get('/admin/users', { params }),
  setUserActive: (id, isActive) => api.patch(`/admin/users/${id}/active`, { isActive }),
  vehicles: (params) => api.get('/admin/vehicles', { params }),
  vehicle: (id) => api.get(`/admin/vehicles/${id}`),
  createVehicle: (b) => api.post('/admin/vehicles', b),
  patchVehicle: (id, b) => api.patch(`/admin/vehicles/${id}`, b),
  drivers: () => api.get('/admin/drivers'),
  routes: () => api.get('/admin/routes'),
  saveRoute: (id, b) => (id ? api.put(`/admin/routes/${id}`, b) : api.post('/admin/routes', b)),
  deleteRoute: (id) => api.delete(`/admin/routes/${id}`),
  stops: (params) => api.get('/admin/stops', { params }),
  saveStop: (id, b, kind) => (id ? api.put(`/admin/stops/${id}`, b, { params: { kind } }) : api.post('/admin/stops', b, { params: { kind } })),
  deleteStop: (id, kind) => api.delete(`/admin/stops/${id}`, { params: { kind } }),
  depots: () => api.get('/admin/depot'),
  saveDepot: (id, b) => (id ? api.put(`/admin/depot/${id}`, b) : api.post('/admin/depot', b)),
  deleteDepot: (id) => api.delete(`/admin/depot/${id}`),
  trains: () => api.get('/admin/trains'),
  saveLine: (id, b) => (id ? api.put(`/admin/trains/lines/${id}`, b) : api.post('/admin/trains/lines', b)),
  saveStation: (id, b) => (id ? api.put(`/admin/trains/stations/${id}`, b) : api.post('/admin/trains/stations', b)),
  saveTrainRoute: (id, b) => (id ? api.put(`/admin/trains/routes/${id}`, b) : api.post('/admin/trains/routes', b)),
  saveService: (id, b) => (id ? api.put(`/admin/trains/services/${id}`, b) : api.post('/admin/trains/services', b)),
  verification: () => api.get('/admin/verification'),
  verify: (driverId, action, note) => api.post(`/admin/verification/${driverId}/action`, { action, note }),
  documentUrl: (id) => `${import.meta.env.VITE_API_URL || '/api'}/admin/documents/${id}/file`,
  registerBus: (fd) => api.post('/admin/register/bus', fd, form()),
  registerTrain: (fd) => api.post('/admin/register/train', fd, form()),
  reports: () => api.get('/admin/reports'),
  setReportStatus: (id, status) => api.patch(`/admin/reports/${id}`, { status }),
}
